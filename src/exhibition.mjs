// Original interpretive reading text keyed to the thesis's printed pages.
// This module contains no thesis images, extracted prose, routes, or new coordinates.
const section = (id, title, kind, pages, body, placeIds = [], more = {}) =>
  ({ id, title, kind, pages, body, placeIds, ...more });
const chapter = (id, title, kicker, summary, sections) => ({
  id, title, kicker, summary,
  pages: [...new Set(sections.flatMap(entry => entry.pages))].sort((a, b) => a - b),
  sections,
});
const item = (title, text, placeId, kind) => ({title, text, ...(placeId ? {placeId} : {}), ...(kind ? {kind} : {})});
